export function getIcon(key, className = "icon-svg") {
  const icon = ICONS[key];
  if (!icon) return "";
  if (typeof icon === "string" && icon.startsWith("<svg")) {
    if (className) {
      return icon.replace("<svg ", `<svg class="${className}" `);
    }
    return icon;
  }
  return `<span class="icon-emoji ${className}">${icon}</span>`;
}
